SPACE = 3
ROWS = 9
BASE = 7


def glyph_rows(spec):
    rows = spec.split()
    width = max(len(r) for r in rows)
    rows = [r.ljust(width, ".") for r in rows] + ["." * width] * (ROWS - len(rows))
    return rows, width


def build(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    glyphs = {ch: glyph_rows(spec) for ch, spec in G.items()}
    cols = 16
    cell_w = max(w for _, w in glyphs.values()) + 1
    sheet = Canvas(cols * cell_w, ((len(glyphs) + cols - 1) // cols) * (ROWS + 1))
    lines = []
    for i, (ch, (rows, w)) in enumerate(glyphs.items()):
        x, y = (i % cols) * cell_w, (i // cols) * (ROWS + 1)
        for ry, row in enumerate(rows):
            for rx, px in enumerate(row):
                if px == "#":
                    sheet.set(x + rx, y + ry, "tinta")
        lines.append(f"char id={ord(ch)} x={x} y={y} width={w} height={ROWS} xoffset=0 yoffset=0 xadvance={w + 1} page=0 chnl=15")
    lines.append(f"char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance={SPACE + 1} page=0 chnl=15")
    sheet.save(os.path.join(out_dir, "aksara_malam.png"))
    header = [
        f'info face="Aksara Malam" size={ROWS} bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1',
        f"common lineHeight={ROWS + 1} base={BASE} scaleW={sheet.w} scaleH={sheet.h} pages=1 packed=0",
        'page id=0 file="aksara_malam.png"',
        f"chars count={len(lines)}",
    ]
    with open(os.path.join(out_dir, "aksara_malam.fnt"), "w") as f:
        f.write("\n".join(header + lines) + "\n")
    assert all(len(r) == w for rows, w in glyphs.values() for r in rows)
    return len(glyphs)
